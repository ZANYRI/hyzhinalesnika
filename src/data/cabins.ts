function makeGallery(folder: string, count: number, baseAlt: string) {
  return Array.from({ length: count }, (_, i) => {
    const num = String(i + 1).padStart(2, "0");
    return {
      src: `/images/${folder}/${num}.jpg`,
      alt: `${baseAlt}, фото ${i + 1}`,
    };
  });
}

